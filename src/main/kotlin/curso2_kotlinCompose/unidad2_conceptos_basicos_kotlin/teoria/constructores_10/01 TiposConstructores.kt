/*
Una clase de Kotlin puede tener un constructor primario, constructores secundarios, ambos o ninguno explícitamente.

Si tiene constructor primario, NO es necesario tener ningún constructor secundario.

Puede tener cero, uno o varios constructores secundarios.

Si no declaras ningún constructor, Kotlin puede proporcionar un constructor sin argumentos (si las condiciones del caso lo permiten).

 Regla fácil de recordar:

Constructor primario → 0, 1 o varios secundarios.

No es obligatorio tener un secundario.

- Forma de crear un objeto: usar constructor primario
- Forma/s alternativa/s de crear un objeto: usar constructor/es secundario/s
 */